void bench(void) { *(volatile unsigned long *)0x7fffe0 = 1; if (run()) abort(); }
#else
#include <stdio.h>
int main(void) { int b = run(); printf("rfc8439: %s (%d)\n", b ? "NG" : "OK", b); return b; }
#endif
