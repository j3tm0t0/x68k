/* RFC 8439 の固定ベクタ (2.3.2 ChaCha20 ブロック、2.4.2 暗号化、2.5.2 Poly1305) で cp68k を確かめる。
 * ホスト: cc -I.. rfc8439.c ../cp68k.c && ./a.out   (C 版)
 * csim:   mk.sh rfc -DCP68K_ASM -DCSIM rfc8439.c ../cp68k.c ../chacha68k.s ../poly68k.s  (asm 版。違えば abort)
 * 2.4.2 は 114 バイトを 1 ブロックずつ足した長さ (1..114) と、2.5.2 の Poly1305 は表引き版も (同じ鍵で長いメッセージ) */
#include <string.h>
#include "cp68k.h"
